func init() {
	ompCmd.PersistentFlags().StringVar(&ompProfile, "profile", "", "Target an omp named profile (as if OMP_PROFILE were exported)")
	ompListCmd.Flags().BoolVar(&ompListJSON, "json", false, "Output as JSON")
	ompUnlinkCmd.Flags().BoolVar(&ompUnlinkAll, "all", false, "Remove everything ccp set up in omp")
	ompCmd.AddCommand(ompLinkCmd)
	ompCmd.AddCommand(ompUnlinkCmd)
	ompCmd.AddCommand(ompSyncCmd)
	ompCmd.AddCommand(ompListCmd)
	rootCmd.AddCommand(ompCmd)
}

func runOmpLink(cmd *cobra.Command, args []string) error {
	paths, err := config.ResolvePaths()
	if err != nil {
		return err
	}
	if !paths.IsInitialized() {
		return fmt.Errorf("ccp not initialized: run 'ccp init' first")
	}

	if len(args) == 0 {
		return runInteractiveOmpLink(paths)
	}

	result, err := profile.OmpLink(paths, args)
	if err != nil {
		return err
	}

	reportOmpResult(result)
	for _, item := range result.Skipped {
		fmt.Printf("Already linked %s\n", item)
	}
	return nil
}

func runInteractiveOmpLink(paths *config.Paths) error {
	scanner := hub.NewScanner()
	h, err := scanner.Scan(paths.HubDir)
	if err != nil {
		return fmt.Errorf("failed to scan hub: %w", err)
	}

	linked, err := profile.OmpList(paths)
	if err != nil {
		return err
	}
	linkedRefs := make(map[string]bool, len(linked))
	for _, ref := range linked {
		linkedRefs[ref] = true
	}

	offered := make(map[config.HubItemType][]string)
	for _, itemType := range profile.OmpLinkTypes {
		for _, item := range h.GetItems(itemType) {
			if linkedRefs[string(itemType)+"/"+item.Name] {
				continue
			}
			offered[itemType] = append(offered[itemType], item.Name)
		}
	}

	tabs := ompTabs(offered)
	if len(tabs) == 0 {
		fmt.Println("Every hub skill and command is already linked to omp")
		return nil
	}

	fmt.Printf("Link hub items to omp (%s)\n\n", profile.OmpAgentDir())

	refs, err := ompPickRefs(tabs)
	if err != nil || refs == nil {
		return err
	}
	if len(refs) == 0 {
		fmt.Println("No items selected")
		return nil
	}

	result, err := profile.OmpLink(paths, refs)
	if err != nil {
		return err
	}

	reportOmpResult(result)
	return nil
}

func runInteractiveOmpUnlink(paths *config.Paths) error {
	linked, err := profile.OmpList(paths)
	if err != nil {
		return err
	}
	if len(linked) == 0 {
		fmt.Println("No hub items linked to omp")
		return nil
	}

	offered := make(map[config.HubItemType][]string)
	for _, ref := range linked {
		itemType, name, ok := strings.Cut(ref, "/")
		if !ok {
			continue
		}
		offered[config.HubItemType(itemType)] = append(offered[config.HubItemType(itemType)], name)
	}

	fmt.Printf("Unlink hub items from omp (%s)\n\n", profile.OmpAgentDir())

	refs, err := ompPickRefs(ompTabs(offered))
	if err != nil || refs == nil {
		return err
	}
	if len(refs) == 0 {
		fmt.Println("No items selected")
		return nil
	}

	unlinked, err := profile.OmpUnlink(paths, refs)
	if err != nil {
		return err
	}

	for _, item := range unlinked {
		fmt.Printf("Unlinked %s\n", item)
	}
	return nil
}

// ompTabs groups item names by hub type into picker tabs, skipping empty types.
func ompTabs(names map[config.HubItemType][]string) []picker.Tab {
	var tabs []picker.Tab
	for _, itemType := range profile.OmpLinkTypes {
		var items []picker.Item
		for _, name := range names[itemType] {
			items = append(items, picker.Item{ID: name, Label: name})
		}
		if len(items) > 0 {
			tabs = append(tabs, picker.Tab{Name: string(itemType), Items: items})
		}
	}
	return tabs
}

// ompPickRefs runs the tabbed picker, returning selected items as type/name
// refs. A nil slice means the user cancelled.
func ompPickRefs(tabs []picker.Tab) ([]string, error) {
	selections, err := picker.RunTabbed(tabs)
	if err != nil {
		return nil, fmt.Errorf("picker error: %w", err)
	}
	if selections == nil {
		fmt.Println("Cancelled")
		return nil, nil
	}

	var refs []string
	for _, itemType := range profile.OmpLinkTypes {
		for _, name := range selections[string(itemType)] {
			refs = append(refs, string(itemType)+"/"+name)
		}
	}
	return refs, nil
}

func runOmpUnlink(cmd *cobra.Command, args []string) error {
	paths, err := config.ResolvePaths()
	if err != nil {
		return err
	}

	if ompUnlinkAll {
		if len(args) > 0 {
			return fmt.Errorf("--all removes everything; do not name items too")
		}
		removed, err := profile.OmpTeardown(paths)
		if err != nil {
			return err
		}
		for _, path := range removed {
			fmt.Printf("Removed %s\n", path)
		}
		if len(removed) == 0 {
			fmt.Println("Nothing to unlink")
		}
		return nil
	}

	if len(args) == 0 {
		return runInteractiveOmpUnlink(paths)
	}

	unlinked, err := profile.OmpUnlink(paths, args)
	if err != nil {
		return err
	}

	for _, item := range unlinked {
		fmt.Printf("Unlinked %s\n", item)
	}
	if len(unlinked) == 0 {
		fmt.Println("Nothing to unlink")
	}
	return nil
}

func runOmpSync(cmd *cobra.Command, args []string) error {
	paths, err := config.ResolvePaths()
	if err != nil {
		return err
	}
	if !paths.IsInitialized() {
		return fmt.Errorf("ccp not initialized: run 'ccp init' first")
	}

	p, err := resolveOmpProfile(paths, args)
	if err != nil {
		return err
	}

	result, err := profile.OmpSync(paths, p)
	if err != nil {
		return err
	}

	reportOmpResult(result)
	if len(result.Linked) == 0 && len(result.Removed) == 0 && len(result.Context) == 0 {
		fmt.Printf("omp is up to date with profile '%s'\n", p.Name)
	}
	return nil
}

func runOmpList(cmd *cobra.Command, args []string) error {
	paths, err := config.ResolvePaths()
	if err != nil {
		return err
	}

	items, err := profile.OmpList(paths)
	if err != nil {
		return err
	}

	// A named profile is an error when unknown; a missing active profile just
	// means there is nothing to compare against.
	var p *profile.Profile
	if len(args) > 0 {
		p, err = profile.NewManager(paths).Get(args[0])
		if err != nil {
			return fmt.Errorf("failed to get profile: %w", err)
		}
		if p == nil {
			return fmt.Errorf("profile not found: %s", args[0])
		}
	} else {
		p, _ = profile.NewManager(paths).GetActive()
	}

	diff := profile.OmpDiff{}
	context := profile.OmpContextReport{}
	if p != nil {
		diff, err = profile.OmpStatus(paths, p.Manifest)
		if err != nil {
			return err
		}
		context, err = profile.OmpContextStatus(paths, p)
		if err != nil {
			return err
		}
	}

	if ompListJSON {
		out := ompListOutput{
			AgentDir: profile.OmpAgentDir(),
			Linked:   items,
			Missing:  diff.Missing,
			Stale:    diff.Stale,
			Ignored:  diff.Ignored,
		}
		if p != nil {
			out.Profile = p.Name
			out.Unreadable = context.Unreadable
		}
		data, err := json.MarshalIndent(out, "", "  ")
		if err != nil {
			return err
		}
		fmt.Println(string(data))
		return nil
	}

	if len(items) == 0 {
		fmt.Printf("No hub items linked to omp (%s)\n", profile.OmpAgentDir())
		fmt.Println("Link items with: ccp omp link skills/<name>")
	} else {
		fmt.Printf("Hub items linked to omp (%s):\n", profile.OmpAgentDir())
		for _, item := range items {
			fmt.Printf("  %s\n", item)
		}
	}

	if p == nil {
		return nil
	}

	fmt.Println()
	if diff.Empty() && !context.OutOfDate() {
		fmt.Printf("omp matches profile '%s'\n", p.Name)
		for _, state := range context.Current {
			fmt.Printf("  context: %s\n", state)
		}
		reportOmpNotes(diff, context)
		return nil
	}

	fmt.Printf("omp is out of sync with profile '%s':\n", p.Name)
	if len(diff.Missing) > 0 {
		fmt.Printf("  missing: %s\n", summarizeRefs(diff.Missing))
	}
	if len(diff.Stale) > 0 {
		fmt.Printf("  stale:   %s\n", summarizeRefs(diff.Stale))
	}
	for _, state := range context.Stale {
		fmt.Printf("  context: %s\n", state)
	}
	reportOmpNotes(diff, context)
	fmt.Println("  → run 'ccp omp sync' to reconcile")
	return nil
}

// reportOmpNotes prints what no sync can fix: paths ccp did not create, items
// omp ignores, and rules ccp could not read. They persist, so 'list' shows them
// every time.
func reportOmpNotes(diff profile.OmpDiff, context profile.OmpContextReport) {
	for _, state := range context.Occupied {
		fmt.Printf("  note:    %s is occupied by a file ccp did not create\n", state)
	}
	for _, state := range context.Unreadable {
		fmt.Printf("  note:    RULES.md skips unreadable %s\n", state)
	}
	for _, item := range diff.Ignored {
		fmt.Printf("  ignored: %s — linked, but omp ignores it\n", item)
	}
}

// resolveOmpProfile returns the profile named on the command line, or the
// active profile.
func resolveOmpProfile(paths *config.Paths, args []string) (*profile.Profile, error) {
	mgr := profile.NewManager(paths)
	if len(args) == 0 {
		p, err := mgr.GetActive()
		if err != nil {
			return nil, fmt.Errorf("failed to get active profile: %w", err)
		}
		if p == nil {
			return nil, fmt.Errorf("no active profile: specify a profile name or run 'ccp use <profile>'")
		}
		return p, nil
	}

	p, err := mgr.Get(args[0])
	if err != nil {
		return nil, fmt.Errorf("failed to get profile: %w", err)
	}
	if p == nil {
		return nil, fmt.Errorf("profile not found: %s", args[0])
	}
	return p, nil
}

// reportOmpResult prints the changes an omp link or sync pass made, plus the
// notes a sync cannot fix by itself. Already-linked items are reported by 'link'
// only.
func reportOmpResult(result profile.OmpLinkResult) {
	for _, item := range result.Removed {
		fmt.Printf("Removed %s\n", item)
	}
	for _, item := range result.Linked {
		fmt.Printf("Linked %s → %s\n", item, profile.OmpAgentDir())
	}
	for _, note := range result.Notes {
		fmt.Printf("Note %s\n", note)
	}
	for _, item := range result.Context {
		fmt.Printf("Context %s\n", item)
	}
}

// summarizeRefs joins item refs for display, capping the list so a full profile
// (dozens of skills) cannot flood the output.
func summarizeRefs(refs []string) string {
	const max = 8
	if len(refs) <= max {
		return strings.Join(refs, ", ")
	}
	return fmt.Sprintf("%s, +%d more", strings.Join(refs[:max], ", "), len(refs)-max)
}

// ompListOutput is the --json shape of 'ccp omp list'.
type ompListOutput struct {
	AgentDir   string   `json:"agent_dir"`
	Linked     []string `json:"linked"`
	Profile    string   `json:"profile,omitempty"`
	Missing    []string `json:"missing,omitempty"`
	Stale      []string `json:"stale,omitempty"`
	Ignored    []string `json:"ignored,omitempty"`
	Unreadable []string `json:"unreadable,omitempty"`
}
