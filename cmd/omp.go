var ompCmd = &cobra.Command{
	Use:    "omp",
	Short:  "Link hub items to omp (oh-my-pi)",
	Hidden: true,
	Long: `Manage ccp hub links for omp, the oh-my-pi coding agent.

omp reads its own config from ~/.omp/agent/ and only loads ~/.claude when its
enabledProviders setting opts in, so ccp mirrors the hub into omp's own agent
directory — skills/, agents/ and commands/ as links, plus AGENTS.md and
RULES.md. No omp configuration is needed.

Rules travel in RULES.md, not as links: omp surfaces a rule only when its
frontmatter routes it somewhere, and a rule whose frontmatter omp does not honor
is dropped without a word. RULES.md is generated by ccp and injected into every
omp session, which is also how Claude Code treats a rule — always on.

An item omp ignores, such as a skill with no description, is linked anyway and
reported with its reason: a guess about omp's loader must never take
configuration away.

--profile targets an omp named profile (equivalent to exporting OMP_PROFILE).`,
	PersistentPreRunE: func(cmd *cobra.Command, args []string) error {
		if ompProfile == "" {
			return nil
		}
		// omp resolves a named profile from the environment, so targeting one is
		// exactly "as if you had exported OMP_PROFILE". An explicit name that is
		// not a single path element is an error: ccp must not ignore it and write
		// into a tree the user did not ask for.
		name, err := profile.ValidateOmpProfile(ompProfile)
		if err != nil {
			return err
		}
		if name == "" {
			return os.Unsetenv("OMP_PROFILE")
		}
		return os.Setenv("OMP_PROFILE", name)
	},
}

